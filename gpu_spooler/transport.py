"""
SSH transport for task-spooler.

Every remote call goes through a generated ssh config
(~/.task-spooler/ssh_config.{direct,jump}) so that connections are multiplexed
with ControlMaster, including each hop of a ProxyJump chain. Scripts are sent
on stdin to `bash -s`, which avoids quoting through the remote login shell.
Hosts with kind = "local" run the same scripts with a local `bash -s`.
"""

import concurrent.futures
import json
import os
import socket
import subprocess
import tempfile
import threading
import time
from pathlib import Path
from typing import Callable, Iterable, Optional, TypeVar

from gpu_spooler.config import Config, Host, STATE_DIR

NETWORK_CACHE = STATE_DIR / "network.json"
NETWORK_TTL = 300          # seconds a network-mode probe result stays valid
PROBE_TIMEOUT = 2

AUTH_HINTS = (
    "permission denied", "keyboard-interactive", "host key verification failed",
    "too many authentication failures", "verification code",
)

T = TypeVar("T")


def _cm_dir() -> Path:
    """
    Directory for ControlMaster sockets. Unix socket paths are limited to
    ~104 bytes on macOS and ssh appends a 17-byte suffix while creating the
    socket, so fall back to /tmp when the home path is too long.
    """
    d = STATE_DIR / "cm"
    if len(str(d)) + 1 + 40 + 17 > 100:
        d = Path(f"/tmp/ts-cm-{os.getuid()}")
    return d


def auth_hint(stderr: str) -> Optional[str]:
    low = stderr.lower()
    if any(h in low for h in AUTH_HINTS):
        return "authentication failed - run `task --connect` to log in interactively"
    return None


class Transport:
    def __init__(self, cfg: Config):
        self.cfg = cfg
        self.cm_dir = _cm_dir()
        self._mode: Optional[str] = None
        self._mode_ts = 0.0
        self._written: dict[str, Path] = {}
        self._lock = threading.Lock()

    # ── ssh config generation ────────────────────────────────────────────────

    def render_ssh_config(self, mode: str) -> str:
        cfg = self.cfg
        jump = mode == "jump"
        out = ["# Generated by task-spooler from " + cfg.source_label + ". Do not edit.", ""]

        def block(h: Host, persist: Optional[str], proxy: Optional[str]) -> None:
            out.append(f"Host {h.alias}")
            if h.hostname:
                out.append(f"  HostName {h.hostname}")
            if h.user:
                out.append(f"  User {h.user}")
            if h.port:
                out.append(f"  Port {h.port}")
            if proxy:
                out.append(f"  ProxyJump {proxy}")
            if persist:
                out.append(f"  ControlPersist {persist}")
            out.append("")

        if jump:
            seen = set()
            for hops in cfg.jumps.values():
                prev = None
                for name in hops:
                    if name not in seen:
                        block(cfg.hosts[name], cfg.jump_control_persist, prev)
                        seen.add(name)
                    prev = cfg.hosts[name].alias
        for h in cfg.hosts.values():
            if h.is_local or h.role == "jump":
                continue
            proxy = cfg.chain(h)[-1].alias if (jump and h.jump) else None
            block(h, None, proxy)

        out += [
            "Host *",
            "  BatchMode yes",
            "  StrictHostKeyChecking accept-new",
            "  LogLevel ERROR",
            "  ConnectTimeout 10",
            "  ServerAliveInterval 30",
            "  ServerAliveCountMax 3",
            "  ControlMaster auto",
            f"  ControlPath {self.cm_dir}/%C",
            f"  ControlPersist {cfg.control_persist}",
        ]
        if cfg.identity_file:
            out.append(f"  IdentityFile {os.path.expanduser(cfg.identity_file)}")
        for opt in cfg.extra_options:
            k, _, v = opt.partition("=")
            out.append(f"  {k.strip()} {v.strip()}")
        user_cfg = Path.home() / ".ssh" / "config"
        if user_cfg.exists():
            out.append(f"  Include {user_cfg}")
        return "\n".join(out) + "\n"

    def ssh_config(self, mode: Optional[str] = None) -> Path:
        """Path to the generated ssh config for a mode, (re)writing it if stale."""
        mode = mode or self.mode()
        with self._lock:
            if mode in self._written:
                return self._written[mode]
            path = STATE_DIR / f"ssh_config.{mode}"
            text = self.render_ssh_config(mode)
            STATE_DIR.mkdir(parents=True, exist_ok=True)
            self.cm_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
            try:
                current = path.read_text()
            except OSError:
                current = None
            if current != text:
                tmp = path.with_name(f"{path.name}.{os.getpid()}.tmp")
                tmp.write_text(text)
                os.replace(tmp, path)
            self._written[mode] = path
            return path

    # ── network mode ─────────────────────────────────────────────────────────

    def _probe_target(self) -> Optional[tuple[str, int]]:
        if self.cfg.probe:
            host, _, port = self.cfg.probe.partition(":")
            return host, int(port or 22)
        for h in self.cfg.workers():
            if h.jump and not h.is_local:
                return (h.hostname or h.name), (h.port or 22)
        return None

    def mode(self, refresh: bool = False) -> str:
        """Resolve the network mode: direct or jump."""
        if self.cfg.mode in ("direct", "jump"):
            return self.cfg.mode
        target = self._probe_target()
        if target is None:
            return "direct"
        now = time.time()
        if not refresh and self._mode and now - self._mode_ts < NETWORK_TTL:
            return self._mode
        if not refresh:
            cached = self.cached_mode()
            if cached:
                self._mode, self._mode_ts = cached
                return self._mode
        try:
            socket.create_connection(target, timeout=PROBE_TIMEOUT).close()
            mode = "direct"
        except OSError:
            mode = "jump"
        self._mode, self._mode_ts = mode, now
        try:
            STATE_DIR.mkdir(parents=True, exist_ok=True)
            NETWORK_CACHE.write_text(json.dumps(
                {"mode": mode, "ts": now, "probe": f"{target[0]}:{target[1]}"}))
        except OSError:
            pass
        return mode

    def cached_mode(self) -> Optional[tuple[str, float]]:
        """Fresh cached probe result, without probing."""
        target = self._probe_target()
        try:
            d = json.loads(NETWORK_CACHE.read_text())
            if (target and d.get("probe") == f"{target[0]}:{target[1]}"
                    and time.time() - d["ts"] < NETWORK_TTL and d["mode"] in ("direct", "jump")):
                return d["mode"], d["ts"]
        except (OSError, ValueError, KeyError, TypeError):
            pass
        return None

    def describe_mode(self, probe: bool = True) -> str:
        """Human-readable network mode, e.g. 'jump (auto)'."""
        if self.cfg.mode != "auto":
            return f"{self.cfg.mode} (forced)"
        if self._probe_target() is None:
            return "direct (auto, no jump hosts)"
        if probe:
            return f"{self.mode()} (auto)"
        cached = self.cached_mode()
        return f"{cached[0]} (auto)" if cached else "auto (not probed)"

    # ── running commands ─────────────────────────────────────────────────────

    def argv(self, host: Host) -> list[str]:
        if host.is_local:
            return ["bash", "-s"]
        return ["ssh", "-F", str(self.ssh_config()), host.alias, "bash -s"]

    def run(self, host: Host, script: str, timeout: float = 30) -> tuple[int, str, str]:
        """
        Run a bash script on a host. Returns (rc, stdout, stderr); rc is 255
        for connection failures and 124 on timeout.
        """
        # stderr goes to a file rather than a pipe: a ControlMaster's ProxyJump
        # child can inherit it and keep the pipe open for ControlPersist.
        with tempfile.TemporaryFile() as err:
            try:
                r = subprocess.run(
                    self.argv(host), input=script.encode(), stdout=subprocess.PIPE,
                    stderr=err, timeout=timeout,
                    cwd=str(Path.home()),
                )
                rc, out = r.returncode, r.stdout
            except subprocess.TimeoutExpired as e:
                rc, out = 124, e.stdout or b""
            except OSError as e:
                return 255, "", str(e)
            err.seek(0)
            stderr = err.read().decode(errors="replace")
        if rc == 124 and not stderr:
            stderr = f"timed out after {timeout:.0f}s"
        return rc, out.decode(errors="replace"), stderr

    def popen(self, host: Host, **kw) -> subprocess.Popen:
        """Start `bash -s` on a host; the caller writes the script to stdin."""
        return subprocess.Popen(self.argv(host), stdin=subprocess.PIPE, **kw)

    def fan_out(self, hosts: Iterable[Host], fn: Callable[[Host], T],
                workers: int = 16) -> dict[str, T]:
        """Call fn(host) for each host in parallel, after warming jump chains."""
        hosts = list(hosts)
        self.warm_up(hosts)
        out: dict[str, T] = {}
        if not hosts:
            return out
        with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
            futs = {pool.submit(fn, h): h for h in hosts}
            for f in concurrent.futures.as_completed(futs):
                out[futs[f].name] = f.result()
        return out

    def chains_in_use(self, hosts: Iterable[Host]) -> list[str]:
        seen = []
        for h in hosts:
            if h.jump and not h.is_local and h.jump not in seen:
                seen.append(h.jump)
        return seen

    def warm_up(self, hosts: Iterable[Host]) -> None:
        """
        In jump mode, open the master connection for each chain serially so a
        parallel fan-out doesn't race to create the same hop masters.
        """
        hosts = list(hosts)
        if self.mode() != "jump":
            return
        for chain in self.chains_in_use(hosts):
            last = self.cfg.hosts[self.cfg.jumps[chain][-1]]
            self.run(last, "true", timeout=60)

    # ── interactive helpers ──────────────────────────────────────────────────

    def interactive_argv(self, host: Host) -> list[str]:
        if host.is_local:
            return [os.environ.get("SHELL", "bash"), "-l"]
        return ["ssh", "-F", str(self.ssh_config()), "-o", "BatchMode=no", host.alias]

    def connect(self, hosts: Iterable[Host]) -> int:
        """
        Interactively open each hop of every jump chain in use (so a password
        or OTP can be typed once). Returns the number of failed hops.
        """
        mode = self.mode(refresh=True)
        hosts = list(hosts)
        targets: list[Host] = []
        if mode == "jump":
            for chain in self.chains_in_use(hosts):
                for name in self.cfg.jumps[chain]:
                    if self.cfg.hosts[name] not in targets:
                        targets.append(self.cfg.hosts[name])
        cfg_path = str(self.ssh_config(mode))
        failures = 0
        for h in targets:
            label = h.alias + (f" ({h.hostname})" if h.hostname else "")
            print(f"Connecting to {label} ...", flush=True)
            rc = subprocess.call(
                ["ssh", "-F", cfg_path, "-o", "BatchMode=no", h.alias, "true"])
            if rc != 0:
                print(f"  failed (ssh exit {rc})")
                failures += 1
                break
            print("  ok")
        return failures
